"""Package an already completed local Bora viewer for static GitHub Pages.

No inference, training, downloads, job submission, or remote execution occurs.
The final classifier and the completed classifier comparison share image assets.
"""
import argparse
import copy
import csv
import hashlib
import io
import json
from pathlib import Path
import re
import shutil
import tempfile

ROOT = Path(__file__).resolve().parents[1]
PANELS = ("original", "expert", "tiles", "converted", "bora")
METHODS = {
    "P04": ("neighbor-context", "Neighbor context"),
    "P12": ("orthogonal-nuisance-separation", "Orthogonal nuisance separation"),
    "C03-22": ("latent-density-fusion", "Latent density fusion"),
    "P02": ("covariance-geometry", "Covariance geometry"),
    "C03-52": ("coded-residual", "Coded residual"),
}
SUMMARY_FIELDS = ["units", "top1", "balanced_accuracy", "recall_by_role",
    "trained_role_count", "truth_roles_absent_from_training", "mean_final_geojson_iou",
    "mean_raw_raster_iou", "mean_cached_deployment_seconds", "mean_head_seconds", "per_dataset"]


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2, ensure_ascii=False) + "\n")


def clean(value):
    """Refuse machine-local paths and credentials in the public data payload."""
    if isinstance(value, dict):
        return {k: clean(v) for k, v in value.items()}
    if isinstance(value, list):
        return [clean(v) for v in value]
    if isinstance(value, str) and re.search(r"/Users/|/home/|/mnt/|gh[pousr]_[A-Za-z0-9]{20}|hf_[A-Za-z0-9]{20}", value):
        raise ValueError("Private path or credential-like content in viewer metadata")
    return value


def csv_scores(data):
    out = io.StringIO()
    fields = ["case", "dataset", "split", "method", "name", "final_geojson_iou",
              "raw_raster_iou", "group_accuracy", "cached_seconds", "mpp_x", "mpp_y",
              "height", "width", "boundary_segments_before", "boundary_segments_after"]
    writer = csv.DictWriter(out, fieldnames=fields)
    writer.writeheader()
    for c in data["cases"]:
        for m in c["models"]:
            writer.writerow(dict(case=c["case"], dataset=c["dataset"], split=c["split"],
                method=m["id"], name=m["name"], final_geojson_iou=m["iou"],
                raw_raster_iou=m["raw_iou"], group_accuracy=m["group_top1"],
                cached_seconds=m["seconds"], mpp_x=c["native_mpp_xy"][0],
                mpp_y=c["native_mpp_xy"][1], height=c["native_shape_yx"][0],
                width=c["native_shape_yx"][1],
                boundary_segments_before=m["boundary_segments_before"],
                boundary_segments_after=m["boundary_segments_after"]))
    return out.getvalue()


def build(source, output):
    source = source.resolve()
    data_path = source / "data.json"
    original = json.loads(data_path.read_text())
    if len(original["cases"]) != original["cohort_cases"]:
        raise ValueError("Incomplete source cohort")
    if len({c["case"] for c in original["cases"]}) != len(original["cases"]):
        raise ValueError("Duplicate source cases")
    if any(c["dataset"] == "puma" for c in original["cases"]):
        raise ValueError("PUMA is excluded from the published evaluation cohort")
    if not all(any(m["id"] == "P04" for m in c["models"]) for c in original["cases"]):
        raise ValueError("Missing selected P04 output")
    if output.exists() and not (output / ".bora-viewer-site").exists():
        raise FileExistsError("Refusing to replace a directory not created by this builder")
    output.parent.mkdir(parents=True, exist_ok=True)
    copied = {}
    with tempfile.TemporaryDirectory(prefix=".site-build-", dir=output.parent) as temp:
        site = Path(temp) / "site"
        site.mkdir()
        (site / ".bora-viewer-site").write_text("Bora static viewer; generated by tools/build_public_viewer.py\n")
        for name in ["viewer.js", "viewer.css", "attribution.html", "DATA_LICENSES.md"]:
            shutil.copy2(ROOT / "web" / name, site / name)
        archive = {k: copy.deepcopy(original[k]) for k in ["cases", "roles", "colours",
            "cohort_cases", "threshold_native_pixels", "split_counts", "dataset_counts"]}
        archive["evaluation_policy"] = dict(development_evaluation=True, excluded_datasets=["puma"])
        archive["models"] = []
        archive["mechanisms"] = []
        for m in original["models"]:
            slug, name = METHODS[m["id"]]
            row = {k: copy.deepcopy(m[k]) for k in SUMMARY_FIELDS}
            row.update(id=slug, name=name)
            archive["models"].append(row)
            description = m["description"].replace("parent class evidence", "class evidence").replace("parent tissue alternatives", "tissue alternatives")
            archive["mechanisms"].append(dict(id=slug, name=name, description=description))
        for c in archive["cases"]:
            old = next(row for row in original["cases"] if row["case"] == c["case"])
            c["asset"] = "../assets/" + c["case"]
            for panel in PANELS:
                src = (source / old["asset"] / (panel + ".jpg")).resolve()
                dst = site / "assets" / c["case"] / src.name
                dst.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(src, dst)
                copied[dst.relative_to(site).as_posix()] = sha(src)
            for m in c["models"]:
                src = source / c["case"] / (m["id"] + ".jpg")
                slug, name = METHODS[m["id"]]
                rel = "previews/" + c["case"] + "/" + slug + ".jpg"
                dst = site / rel
                dst.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(src, dst)
                copied[rel] = sha(src)
                m["preview"] = "../" + rel
                old_model = next(q for q in old["models"] if q["id"] == m["id"])
                vec = (source / old_model["vector"]).resolve()
                digest = sha(vec)
                rel = "vectors/" + digest + ".geojson"
                dst = site / rel
                if not dst.exists():
                    dst.parent.mkdir(parents=True, exist_ok=True)
                    # Retain the exact original geometry and deployment metadata.
                    payload = json.loads(vec.read_text())
                    clean(payload)
                    shutil.copy2(vec, dst)
                    copied[rel] = digest
                m["vector"] = "../" + rel
                m.update(id=slug, name=name)
                if m["cleanup"]["positive_polygon_parts_below_threshold"] or m["cleanup"]["polygon_holes_below_threshold"]:
                    raise ValueError("Source geometry did not pass the 20-pixel area audit")
        selected = copy.deepcopy(archive)
        for key in ["models", "mechanisms"]:
            selected[key] = [m for m in selected[key] if m["id"] == "neighbor-context"]
        for c in selected["cases"]:
            c["asset"] = c["asset"].removeprefix("../")
            c["models"] = [m for m in c["models"] if m["id"] == "neighbor-context"]
            for m in c["models"]:
                for key in ["vector", "preview"]:
                    m[key] = m[key].removeprefix("../")
        selected["page_kind"] = "selected"
        archive["page_kind"] = "comparison"
        for d, sub, prefix in [(selected, Path("."), ""), (archive, Path("comparison"), "../")]:
            target = site / sub
            target.mkdir(parents=True, exist_ok=True)
            write_json(target / "data.json", clean(d))
            (target / "scores.csv").write_text(csv_scores(d))
            html = (ROOT / "web" / "index.html").read_text().replace("{{ROOT}}", prefix)
            (target / "index.html").write_text(html)
        write_json(site / "BUILD_PROVENANCE.json", dict(
            format="bora-static-viewer-v1",
            source_data_sha256=sha(data_path), selected_classifier="Neighbor context",
            case_count=len(original["cases"]), split_counts=original["split_counts"],
            dataset_counts=original["dataset_counts"], minimum_native_area=20,
            evaluation="Exploratory evaluation; independent final validation remains necessary",
            scientific_results_recomputed=False, model_inference_performed=False,
            images_resized_by_this_builder=False, native_coordinates_preserved=True,
            source_asset_sha256=copied))
        if output.exists():
            shutil.rmtree(output)
        shutil.copytree(site, output)
    print(json.dumps(dict(output=str(output), cases=len(original["cases"]), assets=len(copied))))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", required=True, type=Path, help="Completed cycle-03/viewer directory")
    parser.add_argument("--output", type=Path, default=ROOT / "site")
    args = parser.parse_args()
    build(args.source, args.output)
